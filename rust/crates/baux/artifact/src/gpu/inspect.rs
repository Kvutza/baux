//! Multi-target, multi-layer GPU & kernel evidence inspection, diffing, and
//! bounded slicing.
//!
//! Supports NVIDIA ELF64 `.cubin` (`sm_75`, `sm_80`, `sm_89`, `sm_90a`,
//! `sm_100`), disassembled SASS (`.sass`), virtual ISA (`.ptx`), Apple Silicon
//! `MTLBinaryArchive` universal Mach-O (`G13`..`G17` + `air64` LLVM bitcode),
//! and specialized shader sources.

#[path = "inspect/binary.rs"]
mod binary;
#[path = "inspect/source.rs"]
mod source;

pub use binary::{inspect_archive, inspect_cubin};
pub use source::{inspect_ir, inspect_ptx, inspect_sass, inspect_shader};

use baux::artifact::json::{Value, json};
use source::has_word;
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct HazardCounts {
    pub spill_ops: u64,
    pub fp64_ops: u64,
    pub rcp_div_ops: u64,
    pub trap_ops: u64,
    pub bsync_ops: u64,
    pub tensor_ops: u64,
    pub async_copy_ops: u64,
}

impl HazardCounts {
    pub fn to_json(&self) -> Value {
        json!({
            "spill_ops": self.spill_ops,
            "fp64_ops": self.fp64_ops,
            "rcp_div_ops": self.rcp_div_ops,
            "trap_ops": self.trap_ops,
            "bsync_ops": self.bsync_ops,
            "tensor_ops": self.tensor_ops,
            "async_copy_ops": self.async_copy_ops,
        })
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KernelEvidence {
    pub name: String,
    pub backend: String,
    pub target: String,
    pub layer: String,
    pub code_bytes: u64,
    pub static_insns: u64,
    pub gpr_count: u64,
    pub uniform_regs: u64,
    pub shared_bytes: u64,
    pub frame_spill_bytes: u64,
    pub hazards: HazardCounts,
}

impl KernelEvidence {
    pub fn to_json(&self) -> Value {
        json!({
            "name": self.name,
            "backend": self.backend,
            "target": self.target,
            "layer": self.layer,
            "code_bytes": self.code_bytes,
            "static_insns": self.static_insns,
            "gpr_count": self.gpr_count,
            "uniform_regs": self.uniform_regs,
            "shared_bytes": self.shared_bytes,
            "frame_spill_bytes": self.frame_spill_bytes,
            "hazards": self.hazards.to_json(),
        })
    }
}

fn file_kernels(file: &Path, bytes: &[u8]) -> Vec<KernelEvidence> {
    if bytes.starts_with(b"\x7fELF") {
        return inspect_cubin(bytes).unwrap_or_default();
    }
    if bytes.len() >= 4 && binary::u32_be(bytes, 0) == Some(0xcbfe_babe) {
        return inspect_archive(bytes).unwrap_or_default();
    }
    let Ok(text) = std::str::from_utf8(bytes) else {
        return Vec::new();
    };
    let ext = file.extension().and_then(|e| e.to_str()).unwrap_or("");
    if ext == "sass" {
        inspect_sass(text)
    } else if ext == "ptx" || bytes.starts_with(b"//\n// Generated by NVIDIA NVVM") {
        inspect_ptx(text)
    } else if ext == "ll" {
        inspect_ir(text)
    } else if ext == "metal" || ext == "cl" {
        inspect_shader(text, if ext == "cl" { "opencl" } else { "metal" })
    } else {
        Vec::new()
    }
}

/// Inspect a directory of captured GPU artifacts and return the sorted
/// `KernelEvidence` rows.
pub fn directory_kernels(path: &Path) -> Result<Vec<KernelEvidence>, String> {
    let mut files = Vec::new();
    collect_files(path, &mut files)?;
    files.sort();

    let mut kernels = BTreeMap::<String, KernelEvidence>::new();
    for file in files {
        let Ok(bytes) = fs::read(&file) else {
            continue;
        };
        for item in file_kernels(&file, &bytes) {
            merge_kernel(&mut kernels, item);
        }
    }
    Ok(kernels.into_values().collect())
}

/// Inspect a directory of captured GPU artifacts (supporting `records/*.cbor` +
/// `blobs/*.bin` as well as raw `.cubin`, `.sass`, `.ptx`, and Metal `.bin`
/// archives) and produce a unified scorecard.
pub fn inspect_directory(path: &Path) -> Result<Value, String> {
    inspect_filtered(path, None)
}

/// Inspect a directory with an optional kernel substring filter.
pub fn inspect_filtered(path: &Path, filter: Option<&str>) -> Result<Value, String> {
    let kernels = directory_kernels(path)?;
    let (totals, rows) = summarize_kernels(&kernels, filter);
    Ok(json!({
        "schema": "baux.kernel-scorecard.v1",
        "path": path.display().to_string(),
        "kernel_count": rows.len() as u64,
        "totals": totals,
        "kernels": rows,
    }))
}

fn summarize_kernels(kernels: &[KernelEvidence], filter: Option<&str>) -> (Value, Vec<Value>) {
    let mut total_bytes = 0u64;
    let mut total_insns = 0u64;
    let mut total_spills = 0u64;
    let mut total_frame_bytes = 0u64;
    let mut total_fp64 = 0u64;
    let mut total_rcp = 0u64;
    let mut total_trap = 0u64;
    let mut total_bsync = 0u64;
    let mut total_tensor = 0u64;

    let rows: Vec<Value> = kernels
        .iter()
        .filter(|k| filter.is_none_or(|pat| k.name.contains(pat)))
        .map(|k| {
            total_bytes += k.code_bytes;
            total_insns += k.static_insns;
            total_spills += k.hazards.spill_ops;
            total_frame_bytes += k.frame_spill_bytes;
            total_fp64 += k.hazards.fp64_ops;
            total_rcp += k.hazards.rcp_div_ops;
            total_trap += k.hazards.trap_ops;
            total_bsync += k.hazards.bsync_ops;
            total_tensor += k.hazards.tensor_ops;
            k.to_json()
        })
        .collect();

    (
        json!({
            "code_bytes": total_bytes,
            "static_insns": total_insns,
            "frame_spill_bytes": total_frame_bytes,
            "spill_ops": total_spills,
            "fp64_ops": total_fp64,
            "rcp_div_ops": total_rcp,
            "trap_ops": total_trap,
            "bsync_ops": total_bsync,
            "tensor_ops": total_tensor,
        }),
        rows,
    )
}

fn merge_kernel(map: &mut BTreeMap<String, KernelEvidence>, incoming: KernelEvidence) {
    let key = format!("{}:{}", incoming.backend, incoming.name);
    if let Some(existing) = map.get_mut(&key) {
        if incoming.layer == "native-binary" {
            existing.target = incoming.target;
            existing.layer = incoming.layer;
            existing.code_bytes = incoming.code_bytes;
            existing.static_insns = incoming.static_insns;
            existing.gpr_count = incoming.gpr_count;
            existing.uniform_regs = incoming.uniform_regs;
            existing.shared_bytes = incoming.shared_bytes;
            existing.frame_spill_bytes = incoming.frame_spill_bytes;
        } else if incoming.layer == "disassembly" {
            existing.hazards = incoming.hazards;
            if existing.static_insns == 0 {
                existing.static_insns = incoming.static_insns;
                existing.code_bytes = incoming.code_bytes;
            }
        }
    } else {
        map.insert(key, incoming);
    }
}

/// Diff two captured GPU evidence directories and return only changed kernels +
/// aggregate deltas.
pub fn diff_directories(before_path: &Path, after_path: &Path) -> Result<Value, String> {
    let before = directory_kernels(before_path)?;
    let after = directory_kernels(after_path)?;
    let (totals_before, _) = summarize_kernels(&before, None);
    let (totals_after, _) = summarize_kernels(&after, None);

    let mut b_map = BTreeMap::<String, &KernelEvidence>::new();
    for k in &before {
        b_map.insert(format!("{}:{}", k.backend, k.name), k);
    }
    let mut changed = Vec::new();
    for a in &after {
        let key = format!("{}:{}", a.backend, a.name);
        if let Some(&b) = b_map.get(&key)
            && b != a
        {
            changed.push(json!({
                "name": a.name.clone(),
                "backend": a.backend.clone(),
                "target": a.target.clone(),
                "insns_before": b.static_insns,
                "insns_after": a.static_insns,
                "gpr_before": b.gpr_count,
                "gpr_after": a.gpr_count,
                "frame_spill_before": b.frame_spill_bytes,
                "frame_spill_after": a.frame_spill_bytes,
                "hazards_before": b.hazards.to_json(),
                "hazards_after": a.hazards.to_json(),
            }));
        }
    }

    Ok(json!({
        "schema": "baux.kernel-diff.v1",
        "before_path": before_path.display().to_string(),
        "after_path": after_path.display().to_string(),
        "changed_count": changed.len() as u64,
        "totals_before": totals_before,
        "totals_after": totals_after,
        "changed_kernels": changed,
    }))
}

fn kernel_section<'a>(text: &'a str, kernel: &str) -> Option<&'a str> {
    let sass_hdr = format!(".text.{kernel}:");
    if let Some(pos) = text.find(&sass_hdr) {
        let tail = &text[pos..];
        let end = tail[sass_hdr.len()..]
            .find("\n.text.")
            .map_or(tail.len(), |e| sass_hdr.len() + e);
        return Some(&tail[..end]);
    }
    let llvm_hdr = format!("@{kernel}(");
    if let Some(pos) = text.find(&llvm_hdr) {
        let start = text[..pos].rfind("define ").unwrap_or(pos);
        let tail = &text[start..];
        let end = tail.find("\n}\n").map_or(tail.len(), |e| e + 3);
        return Some(&tail[..end]);
    }
    for hdr in [format!(".entry {kernel}"), format!("kernel void {kernel}")] {
        if let Some(pos) = text.find(&hdr) {
            let tail = &text[pos..];
            let end = tail.find("\n}\n").map_or(tail.len(), |e| e + 3);
            return Some(&tail[..end]);
        }
    }
    None
}

fn matches_hazard(line: &str, pat_upper: &str) -> bool {
    match pat_upper {
        "SPILL" => has_word(line, "LDL") || has_word(line, "STL") || line.contains(".local"),
        "FP64" => {
            has_word(line, "DMUL")
                || has_word(line, "DADD")
                || has_word(line, "DFMA")
                || line.contains(".F64")
                || line.contains(".f64")
        }
        "RCP" => line.contains("MUFU.RCP") || line.contains("div.u32") || line.contains("rem.u32"),
        "TRAP" => line.contains("BPT.TRAP") || line.contains("trap;"),
        "BSYNC" => has_word(line, "BSSY") || has_word(line, "BSYNC"),
        "MMA" => line.contains("HMMA") || line.contains("WGMMA") || line.contains("mma.sync"),
        _ => line.to_ascii_uppercase().contains(pat_upper),
    }
}

fn filter_lines(lines: &[&str], pat: &str, radius: usize) -> Vec<String> {
    let pat_upper = pat.to_ascii_uppercase();
    let mut hits = Vec::new();
    for (idx, line) in lines.iter().enumerate() {
        if !matches_hazard(line, &pat_upper) {
            continue;
        }
        let start = idx.saturating_sub(radius);
        let end = (idx + radius + 1).min(lines.len());
        for (lno, ltxt) in lines[start..end].iter().enumerate() {
            let entry = format!("{:>4}: {ltxt}", start + lno + 1);
            if hits.last() != Some(&entry) {
                hits.push(entry);
            }
            if hits.len() >= 60 {
                return hits;
            }
        }
    }
    hits
}

/// Extract a bounded basic-block or hazard instruction window (max 60 lines)
/// for a single kernel.
pub fn slice_kernel(
    path: &Path,
    kernel: &str,
    filter: Option<&str>,
    context_lines: usize,
) -> Result<Value, String> {
    let mut files = Vec::new();
    collect_files(path, &mut files)?;
    files.sort();
    let radius = context_lines.min(25);

    for file in files {
        let Ok(bytes) = fs::read(&file) else {
            continue;
        };
        let Ok(text) = std::str::from_utf8(&bytes) else {
            continue;
        };
        let Some(section) = kernel_section(text, kernel) else {
            continue;
        };
        let lines: Vec<&str> = section.lines().collect();
        let selected: Vec<String> = if let Some(pat) = filter {
            filter_lines(&lines, pat, radius)
        } else {
            lines
                .iter()
                .take(60)
                .enumerate()
                .map(|(i, l)| format!("{:>4}: {l}", i + 1))
                .collect()
        };

        return Ok(json!({
            "schema": "baux.kernel-slice.v1",
            "source_file": file.display().to_string(),
            "kernel": kernel,
            "filter": filter.unwrap_or("head"),
            "total_kernel_lines": lines.len() as u64,
            "returned_lines": selected.len() as u64,
            "slice": selected,
        }));
    }
    Err(format!("kernel {kernel:?} not found in {}", path.display()))
}

fn collect_files(path: &Path, out: &mut Vec<std::path::PathBuf>) -> Result<(), String> {
    let meta =
        fs::symlink_metadata(path).map_err(|e| format!("inspect {}: {e}", path.display()))?;
    if meta.is_file() {
        out.push(path.to_path_buf());
        return Ok(());
    }
    if !meta.is_dir() {
        return Ok(());
    }
    for entry in fs::read_dir(path).map_err(|e| format!("read {}: {e}", path.display()))? {
        let entry = entry.map_err(|e| e.to_string())?;
        let ftype = entry.file_type().map_err(|e| e.to_string())?;
        if ftype.is_symlink() {
            continue;
        }
        let child = entry.path();
        if ftype.is_dir() {
            collect_files(&child, out)?;
        } else if ftype.is_file() {
            out.push(child);
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ptx_inspect() {
        let ptx = r#"
.version 8.0
.target sm_90a
.address_size 64

.visible .entry hopper_gemm() {
    .reg .b32 %r<48>;
    .reg .f32 %f<64>;
    .shared .align 16 .b8 smem[16384];
    .local .align 8 .b8 lmem[32];
    div.u32 %r1, %r2, 32;
    ld.local.f32 %f1, [lmem];
    cp.async.cg.shared.global [smem], [%r3], 16;
    wgmma.mma_async.sync.aligned.m64n64k16.f32.f16.f16 {%f1, %f2}, desc_a, desc_b, 1, 1, 1;
    trap;
    ret;
}
"#;
        let items = inspect_ptx(ptx);
        assert_eq!(items.len(), 1);
        let k = &items[0];
        assert_eq!(k.name, "hopper_gemm");
        assert_eq!(k.target, "sm_90a");
        assert_eq!(k.layer, "virtual-isa");
        assert_eq!(k.gpr_count, 112);
        assert_eq!(k.shared_bytes, 16384);
        assert_eq!(k.frame_spill_bytes, 32);
        assert_eq!(k.hazards.rcp_div_ops, 1);
        assert_eq!(k.hazards.spill_ops, 1);
        assert_eq!(k.hazards.async_copy_ops, 1);
        assert_eq!(k.hazards.tensor_ops, 1);
        assert_eq!(k.hazards.trap_ops, 1);
    }

    #[test]
    fn sass_inspect() {
        let sass = r#"
.text.pisa_attention:
        /*0000*/                   S2R R0, SR_TID.X ;
        /*0010*/                   MUFU.RCP R4, R4 ;
        /*0020*/                   LDL R5, [R1+0x10] ;
        /*0030*/                   STL [R1+0x10], R5 ;
        /*0040*/                   DMUL R6, R6, R8 ;
        /*0050*/                   BSSY B0, `(.L_x_1) ;
        /*0060*/                   HMMA.1688.F32 R4, R14, R24, R4 ;
        /*0070*/                   BSYNC B0 ;
        /*0080*/                   BPT.TRAP 0x1 ;
        /*0090*/                   EXIT ;
"#;
        let items = inspect_sass(sass);
        assert_eq!(items.len(), 1);
        let k = &items[0];
        assert_eq!(k.name, "pisa_attention");
        assert_eq!(k.static_insns, 10);
        assert_eq!(k.hazards.rcp_div_ops, 1);
        assert_eq!(k.hazards.spill_ops, 2);
        assert_eq!(k.hazards.fp64_ops, 1);
        assert_eq!(k.hazards.bsync_ops, 2);
        assert_eq!(k.hazards.tensor_ops, 1);
        assert_eq!(k.hazards.trap_ops, 1);

        let dir = tempfile::tempdir().unwrap();
        let sass_path = dir.path().join("sample.sass");
        fs::write(&sass_path, sass).unwrap();
        let slice = slice_kernel(dir.path(), "pisa_attention", Some("spill"), 1).unwrap();
        assert_eq!(slice["kernel"].as_str(), Some("pisa_attention"));
        let count = slice["returned_lines"].as_u64().unwrap();
        assert!((1..=6).contains(&count));
    }
}
